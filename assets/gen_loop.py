#!/usr/bin/env python3
"""Regenerate the looping "working in the shell" block in assets/tmux.svg.

Edit COMMANDS below and run:  python3 assets/gen_loop.py
Everything between the LOOP-START / LOOP-END markers in the SVG is replaced.
"""
import html
import random
import re
from pathlib import Path

SVG = Path(__file__).with_name("tmux.svg")

CW = 8.4          # monospace char width at 14px (measured)
X0 = 4 * CW       # command starts after "~ $ "
Y0 = 290          # prompt line inside the right pane group
LH = 20           # line height
START = 4.8       # seconds, after the intro finishes
TYPE_MS = (0.045, 0.14)  # per-keystroke delay range

# (command, [output lines]); each output line is a list of (class, text)
COMMANDS = [
    ("rg -n 'ctx.Done' --type go", [
        [("fg0 b", "internal/raft/node.go")],
        [("fg4", "142:"), ("fg1", "    case <-"), ("fg0 b", "ctx.Done"), ("fg1", "():")],
        [("fg0 b", "internal/wal/sync.go")],
        [("fg4", "58:"), ("fg1", "     case <-"), ("fg0 b", "ctx.Done"), ("fg1", "():")],
    ]),
    ("kubectl get pods -n platform", [
        [("fg4", "NAME              READY  STATUS")],
        [("fg1", "api-7d9f8-x2k4p   1/1    "), ("fg0 b", "Running")],
        [("fg1", "api-7d9f8-q8mzn   1/1    "), ("fg0 b", "Running")],
        [("fg1", "worker-5c6b-tn2   1/1    "), ("fg0 b", "Running")],
    ]),
    ("go test -race ./...", [
        [("fg0 b", "ok  "), ("fg1", "  zvdy/internal/raft   1.82s")],
        [("fg0 b", "ok  "), ("fg1", "  zvdy/internal/wal    0.41s")],
        [("fg0 b", "ok  "), ("fg1", "  zvdy/pkg/ring        0.09s")],
    ]),
    ("git status -sb", [
        [("fg0 b", "## main"), ("fg4", "...origin/main [ahead 2]")],
        [("fg2", " M "), ("fg1", "internal/raft/node.go")],
        [("fg2", "?? "), ("fg1", "internal/raft/snapshot.go")],
    ]),
    ("cargo build --release", [
        [("fg0 b", "   Compiling "), ("fg1", "kvasir v0.4.0")],
        [("fg0 b", "    Finished "), ("fg1", "release in 41.2s")],
    ]),
    ("kubectl rollout status deploy/api", [
        [("fg1", "Waiting for rollout: 1 of 3 updated")],
        [("fg1", "deployment \"api\" "), ("fg0 b", "successfully rolled out")],
    ]),
    ("journalctl -u zvdy -n 2 --no-pager", [
        [("fg4", "nov 20 21:52 "), ("fg1", "raft: elected leader")],
        [("fg4", "nov 20 21:52 "), ("fg1", "wal: fsync p99=1.3ms")],
    ]),
]


def tspans(parts):
    return "".join(
        f'<tspan class="{c}">{html.escape(t, quote=False)}</tspan>' for c, t in parts
    )


def fmt(x):
    return f"{x:.3f}".rstrip("0").rstrip(".")


def build():
    rnd = random.Random(7)
    segs, t = [], 0.0
    for cmd, out in COMMANDS:
        think = rnd.uniform(0.5, 1.0)                  # pause before typing
        keys = [rnd.uniform(*TYPE_MS) for _ in cmd]
        if " " in cmd:                                 # little hesitation after the verb
            keys[cmd.index(" ")] += 0.25
        typing = think + sum(keys)
        enter = typing + 0.25                          # beat before pressing enter
        hold = 2.0 + 0.25 * len(out)                   # time to "read" output
        segs.append((t, cmd, out, think, keys, enter, hold))
        t += enter + hold
    cycle = t

    o = ['    <!-- LOOP-START (generated by assets/gen_loop.py) -->']
    o.append(f'    <rect width="0" height="0"><animate id="clk" attributeName="x" '
             f'from="0" to="0" dur="{fmt(cycle)}s" begin="{START}s;clk.end"/></rect>')
    for i, (t0, cmd, out, think, keys, enter, hold) in enumerate(segs):
        b = f"clk.begin+{fmt(t0)}s"
        seg = enter + hold
        # keystroke timeline -> discrete reveal of the command + cursor position
        times, acc = [0.0], think
        for k in keys:
            times.append(acc)
            acc += k
        dur = enter
        kt = ";".join(fmt(x / dur) for x in times)
        widths = ";".join(fmt(n * CW) for n in range(len(cmd) + 1))
        xs = ";".join(fmt(X0 + n * CW) for n in range(len(cmd) + 1))
        o.append(f'    <clipPath id="c{i}"><rect x="{fmt(X0)}" y="{Y0 - 16}" height="22" width="0">'
                 f'<animate attributeName="width" values="{widths}" keyTimes="{kt}" calcMode="discrete" '
                 f'begin="{b}" dur="{fmt(dur)}s" fill="freeze"/></rect></clipPath>')
        o.append(f'    <g visibility="hidden"><set attributeName="visibility" to="visible" begin="{b}" dur="{fmt(seg)}s"/>')
        o.append(f'      <text x="{fmt(X0)}" y="{Y0}" class="fg1" clip-path="url(#c{i})">{html.escape(cmd, quote=False)}</text>')
        o.append(f'      <rect y="{Y0 - 14}" width="9" height="18" fill="#928374" x="{fmt(X0)}" visibility="hidden">'
                 f'<set attributeName="visibility" to="visible" begin="{b}" dur="{fmt(enter)}s"/>'
                 f'<animate attributeName="x" values="{xs}" keyTimes="{kt}" calcMode="discrete" begin="{b}" dur="{fmt(dur)}s" fill="freeze"/></rect>')
        o.append(f'      <g visibility="hidden"><set attributeName="visibility" to="visible" begin="clk.begin+{fmt(t0 + enter)}s" dur="{fmt(hold)}s"/>')
        y = Y0
        for line in out:
            y += LH
            o.append(f'        <text x="0" y="{y}">{tspans(line)}</text>')
        y += LH
        o.append(f'        <text x="0" y="{y}"><tspan class="fg4">~ </tspan><tspan class="fg0 b">$</tspan></text>')
        o.append(f'        <rect x="28" y="{y - 14}" width="9" height="18" fill="#928374" class="cursor"/>')
        o.append('      </g>')
        o.append('    </g>')
    o.append('    <!-- LOOP-END -->')
    return "\n".join(o), cycle


def main():
    s = SVG.read_text()
    block, cycle = build()
    s, n = re.subn(r"    <!-- LOOP-START.*?<!-- LOOP-END -->", lambda _: block, s, flags=re.S)
    assert n == 1, "LOOP markers not found in tmux.svg"
    SVG.write_text(s)
    print(f"loop: {len(COMMANDS)} commands, {cycle:.1f}s cycle")


if __name__ == "__main__":
    main()
